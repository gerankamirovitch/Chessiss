"""Interface language. Russian text in the code is the key; EN holds its English form.
Values in {braces} are filled in by t(). Russian-only grammar words (the pronouns in the
explanations) are passed as values too, the English templates simply do not use them."""
from __future__ import annotations

import re

LANGUAGES = {"ru": "Русский", "en": "English"}

_language = "ru"
_CYRILLIC = re.compile("[Ѐ-ӿ]")


def set_language(code: str) -> None:
    global _language
    _language = code if code in LANGUAGES else "ru"


def language() -> str:
    return _language


def is_english() -> bool:
    return _language == "en"


def t(text: str, **values) -> str:
    if _language == "en":
        text = EN.get(text, text)
    return text.format(**values) if values else text


def written_in_current_language(text: str) -> bool:
    """Saved explanations keep the language they were written in."""
    return bool(_CYRILLIC.search(text)) != is_english()


